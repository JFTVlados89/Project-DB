BEGIN;

-- 1. СПРАВОЧНИКИ
-- 1.1. Категория товара
CREATE TABLE category (
    category_id   SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(30)  NOT NULL UNIQUE
        CHECK (category_name IN ('Apparel', 'Electronics', 'Footwear', 'Books', 'Home Appliances')),
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

-- 1.2. Поставщик
CREATE TABLE supplier (
    supplier_id CHAR(4) PRIMARY KEY
        CHECK (supplier_id ~ '^S[0-9]{3}$'),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- 1.3. Локация клиента
CREATE TABLE location (
    location_id SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city        VARCHAR(50)  NOT NULL,
    country     VARCHAR(50),
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    UNIQUE (city, country)
);

-- 1.4. Возрастная группа
CREATE TABLE age_group (
    age_group_id SMALLINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    range_code   VARCHAR(5) NOT NULL UNIQUE
        CHECK (range_code IN ('18-24', '25-34', '35-44', '45-54', '55+')),
    created_at   TIMESTAMP NOT NULL DEFAULT now()
);

-- 1.5. Пол клиента
CREATE TABLE gender (
    gender_id   SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gender_name VARCHAR(20) NOT NULL UNIQUE
        CHECK (gender_name IN ('Male', 'Female', 'Non-Binary')),
    created_at  TIMESTAMP   NOT NULL DEFAULT now()
);

-- 1.6. Способ доставки
CREATE TABLE shipping_method (
    shipping_method_id SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_name        VARCHAR(20)  NOT NULL UNIQUE
        CHECK (method_name IN ('Standard', 'Express', 'Overnight')),
    base_cost          NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (base_cost >= 0),
    created_at         TIMESTAMP    NOT NULL DEFAULT now()
);

-- 2. ТОВАР
CREATE TABLE product (
    product_sk    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    CHAR(5)      NOT NULL UNIQUE
        CHECK (product_id ~ '^P[0-9]{4}$'),
    product_name  VARCHAR(50)  NOT NULL,
    category_id   SMALLINT     NOT NULL REFERENCES category,
    supplier_id   CHAR(4)      NOT NULL REFERENCES supplier,
    price         NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    tax_rate      SMALLINT      NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
    stock_level   SMALLINT      NOT NULL DEFAULT 0 CHECK (stock_level BETWEEN 0 AND 500),
    return_rate   NUMERIC(4,2)  NOT NULL DEFAULT 0 CHECK (return_rate >= 0 AND return_rate <= 100),
    created_at    TIMESTAMP     NOT NULL DEFAULT now()
);

-- 3. ИСТОРИЯ ЦЕН (SCD2)
-- (не уверен нужно ли добавлять эту таблицу)
CREATE TABLE product_price_history (
    price_history_id BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_sk       BIGINT        NOT NULL REFERENCES product,
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    tax_rate         SMALLINT      NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
    valid_from       DATE          NOT NULL DEFAULT CURRENT_DATE,
    valid_to         DATE,                          -- NULL = действует сейчас
    created_at       TIMESTAMP     NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    UNIQUE (product_sk, valid_from)
);

-- 4. ТАБЛИЦА ПРОДАЖ
CREATE TABLE sales_record (
    sale_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_sk         BIGINT   NOT NULL REFERENCES product,
    location_id        SMALLINT NOT NULL REFERENCES location,
    age_group_id       SMALLINT NOT NULL REFERENCES age_group,
    gender_id          SMALLINT NOT NULL REFERENCES gender,
    shipping_method_id SMALLINT NOT NULL REFERENCES shipping_method,
    discount           SMALLINT NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 100),
    shipping_cost      NUMERIC(6,2) NOT NULL CHECK (shipping_cost >= 0),
    seasonality        BOOLEAN  NOT NULL,
    popularity_index   SMALLINT NOT NULL CHECK (popularity_index BETWEEN 0 AND 100),
    created_at         TIMESTAMP NOT NULL DEFAULT now()
);

-- 5. ИНДЕКСЫ
CREATE INDEX idx_product_category        ON product (category_id);
CREATE INDEX idx_product_supplier        ON product (supplier_id);
CREATE INDEX idx_price_history_product   ON product_price_history (product_sk);
CREATE INDEX idx_sales_product           ON sales_record (product_sk);
CREATE INDEX idx_sales_location          ON sales_record (location_id);
CREATE INDEX idx_sales_age_group         ON sales_record (age_group_id);
CREATE INDEX idx_sales_gender            ON sales_record (gender_id);
CREATE INDEX idx_sales_shipping_method   ON sales_record (shipping_method_id);

COMMIT;